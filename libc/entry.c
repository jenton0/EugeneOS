/* ============================================================
 * entry.c — точка входу програм користувача EUGENE OS (CRT0)
 *
 * ЩО ТУТ ВИПРАВЛЕНО ПОРІВНЯНО ЗІ СТАРОЮ ВЕРСІЄЮ:
 *
 * 1) ВИРІВНЮВАННЯ СТЕКУ.
 *    SysV ABI вимагає, щоб на вході у функцію виконувалось
 *    (RSP + 8) % 16 == 0. GCC на -O2 покладається на це і генерує
 *    інструкції movaps по стеку — на невирівняній адресі це #GP,
 *    тобто миттєвий виліт програми. Ядро тепер задає AppStackTop
 *    кратним 16, але ми додатково страхуємось через `and $-16, %rsp`,
 *    щоб програма не залежала від того, що саме поклало ядро.
 *
 * 2) ОБНУЛЕННЯ .bss.
 *    `objcopy -O binary` не записує секцію .bss у плоский бінарник
 *    (це NOBITS). Тому всі глобальні змінні без ініціалізатора
 *    (windows[], history_log[], log_count, expl_count...) при старті
 *    містили сміття від попереднього запуску. Тепер обнуляємо руками.
 *
 * 3) _start винесено в окрему секцію .text.entry, яку linker.ld
 *    кладе найпершою — гарантія, що ядро стрибне саме сюди.
 * ============================================================ */

/* Символи задаються у linker.ld */
extern char __bss_start[];
extern char __bss_end[];

extern void gui_main(void);

/* Викликається з _start уже на вирівняному стеку */
__attribute__((used))
void _c_entry(void)
{
    /* volatile, щоб GCC не згорнув цикл у виклик memset — той може
       опинитись де завгодно, а нам треба працювати ще до ініціалізації */
    volatile char *p = (volatile char *)__bss_start;
    volatile char *e = (volatile char *)__bss_end;
    while (p < e) *p++ = 0;

    gui_main();
}

__attribute__((section(".text.entry"), naked, used))
void _start(void)
{
    /* Basic asm (без двокрапок) — саме те, що дозволено в naked-функціях */
    __asm__(
        "and  $-16, %rsp\n\t"   /* примусове вирівнювання на 16 байт   */
        "xor  %rbp, %rbp\n\t"   /* обриваємо ланцюг кадрів стеку       */
        "call _c_entry\n\t"     /* після call (RSP+8)%16==0 — як хоче ABI */
        "xor  %rax, %rax\n\t"   /* syscall 0 = exit                    */
        "int  $0x80\n\t"
        "1: hlt\n\t"            /* сюди керування не повертається      */
        "jmp 1b\n\t"
    );
}